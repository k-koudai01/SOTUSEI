using UnityEngine;

/// <summary>
/// 鍵のインタラクションクラス
/// </summary>
public class KeyInteraction : Interactable
{
    //====================================================================================
    // 変数
    //====================================================================================

    [Header("鍵の設定")]
    [SerializeField]
    private KeyColor keyColor = KeyColor.Red;

    //===================================================================================
    // インタラクト処理
    //===================================================================================

    protected override void Interact()
    {
        Debug.Log("鍵を拾いました。");

        // インベントリに鍵を追加
        InventoryManager.Instance.AddKey(keyColor);

        // 鍵オブジェクトを削除
        Destroy(gameObject);
    }
}
