using UnityEngine;

/// <summary>
/// スイッチを調べたときの個別処理クラス
/// </summary>
public class SwitchInteraction : Interactable
{
    //=====================================================================
    // 変数宣言
    //=====================================================================

    [Header("スイッチ設定")]
    [SerializeField]
    private SwitchController switchController;

    //=====================================================================
    // インタラクト処理
    //=====================================================================

    protected override void Interact()
    {
        switchController.Activate();
    }
}
