using UnityEngine;

/// <summary>
/// 色に応じた鍵付きドアの処理を行うクラス
/// </summary>
public class LockDoorOnColor : MonoBehaviour
{
    //==================================================================
    // 変数
    //==================================================================

    [Header("ドアの設定")]

    [SerializeField]
    private KeyColor doorColor = KeyColor.Red;

    private bool isOpen = false;

    //==================================================================
    // プロパティ
    //==================================================================

    public KeyColor DoorColor => doorColor;

    public bool IsOpen => isOpen;

    //==================================================================
    // ドアを開く処理
    //==================================================================

    public void OpenDoor()
    {
        isOpen = true;

        Debug.Log("ドアを開いた");
    }
}
